// Generates PNG sprite strips + animation config for every character def.
// Usage: node tools/gen-sprites.js
const fs = require('node:fs');
const path = require('node:path');
const { encodePng } = require('./pixel/png');
const { generateCharacter } = require('./pixel/generate');
const { CHARACTERS } = require('./pixel/characters');
const { COUNTS, FPS, REPEAT } = require('./pixel/anims');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'assets', 'characters');

function sheetPng(frames) {
  const w = frames.length * 64, rgba = new Uint8Array(w * 64 * 4);
  frames.forEach((fr, i) => {
    for (let y = 0; y < 64; y++) for (let x = 0; x < 64; x++) {
      const s = (y * 64 + x) * 4, d = (y * w + i * 64 + x) * 4;
      rgba[d] = fr.data[s]; rgba[d + 1] = fr.data[s + 1]; rgba[d + 2] = fr.data[s + 2]; rgba[d + 3] = fr.data[s + 3];
    }
  });
  return encodePng(w, 64, rgba);
}

function main() {
  const characters = {};
  for (const [id, def] of Object.entries(CHARACTERS)) {
    const { anims } = generateCharacter(def);
    const dir = path.join(OUT, def.folder);
    fs.mkdirSync(dir, { recursive: true });
    const cfg = { name: def.title, faculty: def.faculty, folder: def.folder, skillMode: def.skillMode, impact: def.impact, anims: {} };
    for (const anim of Object.keys(COUNTS)) {
      fs.writeFileSync(path.join(dir, anim + '.png'), sheetPng(anims[anim]));
      cfg.anims[anim] = {
        sheet: `assets/characters/${def.folder}/${anim}.png`,
        frameWidth: 64, frameHeight: 64, frameCount: COUNTS[anim], frameRate: FPS[anim], repeat: REPEAT[anim],
      };
    }
    characters[id] = cfg;
  }
  const json = { version: 1, frame: 64, characters };
  fs.writeFileSync(path.join(OUT, 'animations.json'), JSON.stringify(json, null, 2));
  fs.writeFileSync(path.join(OUT, 'animations.js'), '// generated by tools/gen-sprites.js - do not edit\nglobalThis.CHARACTER_ANIMS = ' + JSON.stringify(characters) + ';\n');
  console.log('generated', Object.keys(characters).join(', '));
}

if (require.main === module) main();
module.exports = { main, sheetPng };
