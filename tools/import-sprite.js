// Import externally drawn character sprite PNGs (Aseprite / Piskel / etc.) without touching combat code.
//   node tools/import-sprite.js add <heroId> <file.png> --anim idle --frames 4 [--frame 64x64] [--rate 6] [--repeat loop|once] [--feet auto|<row>] [--scale 2] [--impact <frame>] [--shadow auto]
//   node tools/import-sprite.js remove <heroId> [--anim idle]     node tools/import-sprite.js list|build|check
// Optional: --root <dir> (default public/assets/characters).
const fs = require('node:fs');
const path = require('node:path');
const { decodePng } = require('./pixel/png');

const DEFAULTS = { idle: [6, 'loop'], walk: [12, 'loop'], attack: [12, 'once'], skill: [14, 'once'], hurt: [12, 'once'], death: [12, 'once'], stun: [8, 'loop'] };
const ANIMS = Object.keys(DEFAULTS);
const DEFAULT_ROOT = path.join(__dirname, '..', 'public', 'assets', 'characters');
const WEB_BASE = 'public/assets/characters';

function readPng(file) {
  const buf = fs.readFileSync(file);
  if (buf.readUInt32BE(0) !== 0x89504e47) throw new Error(`${file}: not a PNG`);
  const depth = buf[24], ctype = buf[25];
  if (depth !== 8 || ctype !== 6) throw new Error(`${file}: must be 8-bit RGBA PNG with transparency (got depth ${depth}, colour type ${ctype}). Export as RGBA, not an indexed palette.`);
  return decodePng(buf);
}

// lowest opaque row of the first frame (used for --feet auto)
function lowestOpaqueRow(img, fw, fh) {
  for (let y = fh - 1; y >= 0; y--) for (let x = 0; x < fw; x++) if (img.rgba[(y * img.w + x) * 4 + 3] > 0) return y;
  throw new Error('first frame is fully transparent');
}

function validate(img, { frameWidth: fw, frameHeight: fh, frameCount: n }, file) {
  const errs = [], warns = [];
  if (img.w !== fw * n || img.h !== fh) errs.push(`${file}: sheet is ${img.w}x${img.h} but ${n} frame(s) of ${fw}x${fh} need ${fw * n}x${fh} (frames in one horizontal row)`);
  let transparent = 0, soft = 0;
  for (let i = 3; i < img.rgba.length; i += 4) { if (img.rgba[i] === 0) transparent++; else if (img.rgba[i] < 255) soft++; }
  if (!transparent) errs.push(`${file}: no transparent pixels - the background must be transparent`);
  if (soft) warns.push(`${file}: ${soft} semi-transparent pixels (anti-aliasing blurs pixel art; use hard edges)`);
  return { errs, warns };
}

function loadCfg(root) {
  const f = path.join(root, 'sprites.json');
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, 'utf8')) : { version: 1, characters: {} };
}

function saveCfg(root, cfg) {
  fs.mkdirSync(root, { recursive: true });
  fs.writeFileSync(path.join(root, 'sprites.json'), JSON.stringify(cfg, null, 2) + '\n');
}

// the manifest the game loads, generated from the sprites.json data (the only manifest generator; tools/characters.js reuses it)
function manifestText(cfg) {
  const ext = {};
  for (const [id, c] of Object.entries(cfg.characters)) {
    ext[id] = { anims: {}, impact: c.impact || {} };
    for (const [a, d] of Object.entries(c.anims)) {
      ext[id].anims[a] = { sheet: `${WEB_BASE}/${d.file}`, frameWidth: d.frameWidth, frameHeight: d.frameHeight, frameCount: d.frameCount, frameRate: d.frameRate, repeat: d.repeat, feetRow: d.feetRow, scale: c.scale || 2, ...(d.shadow ? { shadow: d.shadow } : {}) };
    }
  }
  return `// GENERATED by tools/import-sprite.js from sprites.json - do not edit by hand.
// Replaces the sprite art (only) of the listed heroes; stats, skills and combat code are untouched.
(function () {
  var EXTERNAL_SPRITES = ${JSON.stringify(ext, null, 2).replace(/\n/g, '\n  ')};
  globalThis.EXTERNAL_SPRITES = EXTERNAL_SPRITES;
  if (typeof CHARACTER_ANIMS === 'undefined') return;
  for (var id in EXTERNAL_SPRITES) {
    var old = CHARACTER_ANIMS[id] || {};
    CHARACTER_ANIMS[id] = Object.assign({}, old, { anims: EXTERNAL_SPRITES[id].anims, impact: Object.assign({}, old.impact, EXTERNAL_SPRITES[id].impact), external: true });
  }
})();
`;
}

function build(root) {
  const cfg = loadCfg(root);
  saveCfg(root, cfg);
  fs.writeFileSync(path.join(root, 'manifest.js'), manifestText(cfg));
  return Object.keys(cfg.characters);
}

// characters that have a character.json are owned by tools/characters.js; editing them here would create a second source of truth
const managed = (root, id) => fs.existsSync(path.join(root, id, 'character.json'));
function refuseIfManaged(root, id) {
  if (managed(root, id)) throw new Error(`${id} is configured by ${id}/character.json - edit that file and run: node tools/characters.js build`);
}

// ground shadow per frame (for poses that leave the standing spot, e.g. a fall): [dx from frame centre, half-width, alpha]
// footprint = opaque pixels in the 6 rows above the feet line; alpha follows how much of the figure is left (dissolve)
function shadowFrames(img, fw, fh, n, feetRow) {
  const counts = [], rows = [];
  for (let f = 0; f < n; f++) {
    let c = 0, x0 = fw, x1 = -1;
    for (let y = 0; y < fh; y++) for (let x = 0; x < fw; x++) {
      if (!img.rgba[(y * img.w + f * fw + x) * 4 + 3]) continue;
      c++;
      if (y >= feetRow - 5) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); }
    }
    counts.push(c); rows.push(x1 < 0 ? null : [x0, x1]);
  }
  const max = Math.max(...counts);
  let last = [fw / 2 - 14, fw / 2 + 14];
  return rows.map((r, f) => {
    if (r) last = r;
    const rx = Math.min(60, Math.max(14, (last[1] - last[0]) / 2 + 4));
    return [Math.round((last[0] + last[1]) / 2 - fw / 2), Math.round(rx), Math.round(Math.min(1, counts[f] / (max * 0.8)) * 100) / 100];
  });
}

function add(root, id, file, o) {
  refuseIfManaged(root, id);
  const anim = o.anim || 'idle';
  if (!ANIMS.includes(anim)) throw new Error(`--anim must be one of ${ANIMS.join(', ')}`);
  const [fw, fh] = (o.frame || '64x64').split('x').map(Number);
  const frameCount = +(o.frames || 1);
  const img = readPng(file);
  const def = { frameWidth: fw, frameHeight: fh, frameCount };
  const { errs, warns } = validate(img, def, file);
  if (errs.length) throw new Error(errs.join('\n'));
  const cfg = loadCfg(root);
  const ch = (cfg.characters[id] ||= { scale: 2, anims: {} });
  if (o.scale) ch.scale = +o.scale;
  const feet = o.feet === undefined ? (anim === 'idle' ? 'auto' : (ch.anims.idle ? ch.anims.idle.feetRow : 'auto')) : o.feet;
  const feetRow = feet === 'auto' ? lowestOpaqueRow(img, fw, fh) : +feet;
  const rel = `${id}/${anim}.png`;
  fs.mkdirSync(path.join(root, id), { recursive: true });
  fs.copyFileSync(file, path.join(root, rel));
  if (o.impact !== undefined) ch.impact = { ...(ch.impact || {}), [anim]: +o.impact };
  const [rate, rep] = DEFAULTS[anim];
  ch.anims[anim] = { file: rel, ...def, frameRate: +(o.rate || rate), repeat: (o.repeat || rep) === 'loop' ? -1 : 0, feetRow };
  if (o.shadow === 'auto') ch.anims[anim].shadow = shadowFrames(img, fw, fh, frameCount, feetRow);
  saveCfg(root, cfg);
  build(root);
  return { feetRow, warns };
}

function remove(root, id, anim) {
  refuseIfManaged(root, id);
  const cfg = loadCfg(root);
  if (!cfg.characters[id]) throw new Error(`no external sprite for ${id}`);
  if (anim) { delete cfg.characters[id].anims[anim]; if (!Object.keys(cfg.characters[id].anims).length) delete cfg.characters[id]; } else delete cfg.characters[id];
  saveCfg(root, cfg);
  build(root);
}

function check(root) {
  const cfg = loadCfg(root), problems = [];
  for (const [id, c] of Object.entries(cfg.characters)) for (const [a, d] of Object.entries(c.anims)) {
    const f = path.join(root, d.file);
    if (!fs.existsSync(f)) { problems.push(`${id}/${a}: missing ${d.file}`); continue; }
    try { problems.push(...validate(readPng(f), d, `${id}/${a}`).errs); } catch (e) { problems.push(e.message); }
  }
  return problems;
}

function parse(argv) {
  const pos = [], o = {};
  for (let i = 0; i < argv.length; i++) { if (argv[i].startsWith('--')) o[argv[i].slice(2)] = argv[++i]; else pos.push(argv[i]); }
  return { pos, o };
}

if (require.main === module) {
  const { pos, o } = parse(process.argv.slice(2));
  const root = o.root ? path.resolve(o.root) : DEFAULT_ROOT;
  try {
    const [cmd, id, file] = pos;
    if (cmd === 'add') { const r = add(root, id, file, o); r.warns.forEach((w) => console.warn('warning:', w)); console.log(`imported ${id}/${o.anim || 'idle'} (feet row ${r.feetRow}); manifest rebuilt`); }
    else if (cmd === 'remove') { remove(root, id, o.anim); console.log('removed; manifest rebuilt'); }
    else if (cmd === 'build') console.log('manifest rebuilt for:', build(root).join(', ') || '(none - using built-in placeholders)');
    else if (cmd === 'check') { const p = check(root); if (p.length) { console.error(p.join('\n')); process.exit(1); } console.log('ok'); }
    else if (cmd === 'list') console.log(JSON.stringify(loadCfg(root).characters, null, 2));
    else { console.log('usage: add <id> <png> --anim --frames [--frame WxH --rate --repeat --feet --scale] | remove <id> | list | build | check'); process.exit(cmd ? 1 : 0); }
  } catch (e) { console.error('error:', e.message); process.exit(1); }
}
module.exports = { add, remove, build, check, readPng, validate, lowestOpaqueRow, shadowFrames, manifestText, loadCfg, saveCfg };
