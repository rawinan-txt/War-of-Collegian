// Enemy sprites: animation sheets for all nine enemies -> assets/enemies/<id>/<anim>.png + assets/enemies/enemies.js (ENEMY_ANIMS)
// Visual data only. Gameplay stats and abilities live in index.html (enemyTemplates / ENEMY_KITS); this file owns art, timing,
// display scale, anchors and impact frames. The approved static drawings (assets/enemies/<id>/static.png) are frame 0 of every idle sheet.
// Run: node tools/gen-enemies.js   (deterministic)
const fs = require('node:fs');
const path = require('node:path');
const { encodePng } = require('./pixel/png');
const { compose } = require('./enemies/rig');
const { RIGS, ANIMS, COUNTS, FPS, REPEAT, DEATH } = require('./enemies/rigs');

const ROOT = path.join(__dirname, '..');

// display + gameplay-facing visual metadata per enemy
const META = {
  assignment: { name: 'Assignment Monster', role: 'basic', fx: '#f6f2e8' },
  deadline: { name: 'Deadline Monster', role: 'fast', fx: '#ffd23a', proj: 'bang' },
  group: { name: 'Group Project Gang', role: 'tank', fx: '#58b8ff' },
  quiz: { name: 'Midterm Exam', role: 'ranged', fx: '#ffcf3a', proj: 'pencil' },
  final: { name: 'Final Exam', role: 'boss', fx: '#e0334a', scale: 3.3 },
  professor: { name: 'Strict Professor', role: 'ranged', fx: '#e0334a', proj: 'pen' },
  ta: { name: 'Ruthless TA', role: 'fast support', fx: '#52d49a', proj: 'paper' },
  advisor: { name: 'Thesis Advisor', role: 'elite control', fx: '#8d4cf0', proj: 'orb' },
  exammaster: { name: 'Exam Master', role: 'boss', fx: '#a35bff', proj: 'energy', scale: 3.0 },
};

function frameBuf(id, anim, f) {
  const R = RIGS[id];
  const rig = R.draw(R.drawOpts ? R.drawOpts(anim, f) : undefined);
  return compose(rig, R.spec, R.recipe(anim, f));
}
function sheetBuf(id, anim) {
  const n = anim === 'death' && DEATH[id] ? DEATH[id][0] : COUNTS[anim];
  const frames = [];
  for (let f = 0; f < n; f++) frames.push(frameBuf(id, anim, f));
  return frames;
}
function sheetPng(frames) {
  const w = frames.length * 64, rgba = new Uint8Array(w * 64 * 4);
  frames.forEach((fr, i) => {
    for (let y = 0; y < 64; y++) for (let x = 0; x < 64; x++) {
      const s = (y * 64 + x) * 4, d = (y * w + i * 64 + x) * 4;
      rgba[d] = fr.data[s]; rgba[d + 1] = fr.data[s + 1]; rgba[d + 2] = fr.data[s + 2]; rgba[d + 3] = fr.data[s + 3];
    }
  });
  return encodePng(w, 64, rgba);
}

// highest opaque row over the animations a unit shows while alive; the HP bar sits above it (tall sprites like the TA's bun)
function topRow(id) {
  let top = 64;
  for (const anim of ['idle', 'walk', 'attack']) for (const fr of sheetBuf(id, anim)) for (let y = 0; y < top; y++) { let hit = false; for (let x = 0; x < 64 && !hit; x++) hit = fr.data[(y * 64 + x) * 4 + 3] > 0; if (hit) { top = y; break; } }
  return top;
}
// ENEMY_ANIMS registry entry (same shape as CHARACTER_ANIMS so the shared sprite loader and drawing code work unchanged)
function registry() {
  const out = {};
  for (const id of Object.keys(RIGS)) {
    const m = META[id], anims = {};
    for (const anim of ANIMS[id]) {
      const n = anim === 'death' && DEATH[id] ? DEATH[id][0] : COUNTS[anim];
      const fps = anim === 'death' && DEATH[id] ? DEATH[id][1] : FPS[anim];
      anims[anim] = { sheet: `assets/enemies/${id}/${anim}.png`, frameWidth: 64, frameHeight: 64, frameCount: n, frameRate: fps, repeat: REPEAT[anim] };
      if (m.scale) { anims[anim].scale = m.scale; anims[anim].shadow = [[0, 40, 1]]; }
    }
    const sc = m.scale || 2, barY = Math.round(24 - (56 - topRow(id)) * sc - 10);
    out[id] = { name: m.name, enemy: true, role: m.role, barY, impact: { attack: 3, skill: 6 }, anchors: { muzzle: RIGS[id].anchors.muzzle }, fx: { color: m.fx, proj: m.proj || null }, anims };
  }
  return out;
}

function scaled(buf, k) {
  const W = 64 * k, out = Buffer.alloc(W * W * 4);
  for (let y = 0; y < W; y++) for (let x = 0; x < W; x++) {
    const s = (Math.floor(y / k) * 64 + Math.floor(x / k)) * 4, d = (y * W + x) * 4;
    out[d] = buf.data[s]; out[d + 1] = buf.data[s + 1]; out[d + 2] = buf.data[s + 2]; out[d + 3] = buf.data[s + 3];
  }
  return { w: W, rgba: out };
}

function main() {
  for (const id of Object.keys(RIGS)) {
    const dir = path.join(ROOT, 'assets', 'enemies', id);
    fs.mkdirSync(dir, { recursive: true });
    let total = 0;
    for (const anim of ANIMS[id]) {
      const frames = sheetBuf(id, anim);
      fs.writeFileSync(path.join(dir, anim + '.png'), sheetPng(frames));
      total += frames.length;
      if (anim === 'idle') {
        const x8 = scaled(frames[0], 8);
        fs.writeFileSync(path.join(ROOT, 'docs', 'enemy-remodel', id + '_x8.png'), encodePng(x8.w, x8.w, x8.rgba));
      }
    }
    console.log(id.padEnd(11), ANIMS[id].join('/'), total, 'frames');
  }
  fs.writeFileSync(path.join(ROOT, 'assets', 'enemies', 'enemies.js'),
    '// generated by tools/gen-enemies.js - visual registry for enemies (separate from CHARACTER_ANIMS so hero tooling is untouched)\n' +
    'globalThis.ENEMY_ANIMS = ' + JSON.stringify(registry()) + ';\n');
}
if (require.main === module) main();
module.exports = { frameBuf, sheetBuf, registry, META, RIGS, ANIMS };
